import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bootcamp = path.join(root, 'astradocs', 'bootcamp');
const ledgerPath = path.join(bootcamp, 'stories.json');
const outputPath = path.join(bootcamp, 'story-map.md');
const args = process.argv.slice(2);

if (args.some(arg => arg !== '--check')) {
  console.error('Usage: node scripts/render-story-map.mjs [--check]');
  process.exitCode = 2;
} else {
  const ledger = JSON.parse(fs.readFileSync(ledgerPath, 'utf8'));
  const groups = [
    ['Junior', story => story.id.startsWith('US-')],
    ['Midlevel', story => story.id.startsWith('MID-')],
    ['Mid-senior', story => story.id.startsWith('SR-')],
  ];
  const escapeCell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
  const link = (label, target) => target ? `[${escapeCell(label)}](${target})` : '—';
  const implementationLinks = story => story.implementation.length
    ? story.implementation.map((target, index) => {
      const name = path.posix.basename(target.split('#')[0]);
      return link(index === 0 ? `main: ${name}` : name, target);
    }).join('<br>')
    : '—';
  const counts = Object.fromEntries(['planned', 'in_progress', 'implemented', 'verified']
    .map(status => [status, ledger.stories.filter(story => story.status === status).length]));
  const lines = [
    '# Bootcamp story map',
    '',
    '<!-- Generated by scripts/render-story-map.mjs from stories.json. Do not edit by hand. -->',
    '',
    'Use this page to move from a user story to its learning lesson and code. The status is the current ledger state:',
    '`planned` means no implementation claim, `in_progress` means work remains, `implemented` means code exists but final',
    'verification remains, and `verified` means acceptance evidence is recorded. Read the linked plan for the complete',
    'contract and the lesson for worked examples, failure cases, and teach-back practice.',
    '',
    `Current ledger: ${ledger.stories.length} stories — ${counts.verified} verified, ${counts.implemented} implemented, ${counts.in_progress} in progress, ${counts.planned} planned.`,
    '',
  ];
  for (const [name, matches] of groups) {
    const stories = ledger.stories.filter(matches);
    lines.push(`## ${name}`, '', `Stories in this section: ${stories.length}.`, '',
      '| Story | User-visible result | Original plan | Lesson | Implementation | Status |',
      '| --- | --- | --- | --- | --- | --- |');
    for (const story of stories) {
      lines.push(`| ${escapeCell(story.id)} | ${escapeCell(story.title)} | ${link('plan', story.plan)} | ${link('lesson', story.lesson)} | ${implementationLinks(story)} | \`${escapeCell(story.status)}\` |`);
    }
    lines.push('');
  }
  lines.push('The implementation column preserves every code or test link recorded in the ledger. “Main” is the first',
    'ledger entry; support links are additional entry points, not a claim that one file contains the whole feature.', '');
  const rendered = lines.join('\n');
  if (args.includes('--check')) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;
    if (current !== rendered) {
      console.error('astradocs/bootcamp/story-map.md is stale. Run: node scripts/render-story-map.mjs');
      process.exitCode = 1;
    } else {
      console.log('astradocs/bootcamp/story-map.md is current.');
    }
  } else {
    fs.writeFileSync(outputPath, rendered, 'utf8');
    console.log('Wrote astradocs/bootcamp/story-map.md');
  }
}
